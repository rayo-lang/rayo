def measures(instructions, memory, seconds=1.0):
    return {'instructions': instructions, 'peak_memory_bytes': memory, 'wall_seconds': seconds}


class MeasuresTests(unittest.TestCase):
    def test_macos_time_gives_the_instructions_retired_and_the_peak_memory_footprint(self):
        self.assertEqual(macos_measures(MACOS_TIME), {'instructions': 2647118212, 'peak_memory_bytes': 40322368})

    def test_linux_perf_gives_the_instructions_and_time_the_largest_resident_set_in_kilobytes(self):
        perf = '2647118212,,instructions:u,1203000,100.00,,\n'
        self.assertEqual(linux_measures(perf, '51000\n'), {'instructions': 2647118212, 'peak_memory_bytes': 52224000})

    def test_an_instruction_count_the_system_doesnt_give_is_none(self):
        perf = '<not supported>,,instructions:u,0,100.00,,\n'
        self.assertEqual(linux_measures(perf, '51000\n')['instructions'], None)

    def test_a_count_of_no_instructions_which_a_virtual_machine_gives_is_none(self):
        self.assertEqual(macos_measures(MACOS_TIME.replace('2647118212', '0'))['instructions'], None)
        self.assertEqual(linux_measures('0,,instructions:u,0,100.00,,\n', '51000\n')['instructions'], None)

    def test_cachegrind_gives_the_instructions_it_counted_in_its_summary(self):
        self.assertEqual(cachegrind_instructions(CACHEGRIND_OUT), 2647118212)

    def test_cachegrind_runs_rayoc_in_the_same_environment_whatever_the_callers_is(self):
        with mock.patch.dict(os.environ, {'BASE': 'c3953348'}):
            _, with_base = cachegrind_run(['rayoc', '--check', 'loops-200.rayo'], 'cachegrind.out')
        with mock.patch.dict(os.environ, {'HEAD_COMMIT': 'ce2f676e6110', 'BASE_COMMIT': 'c3953348'}):
            _, with_head = cachegrind_run(['rayoc', '--check', 'loops-200.rayo'], 'cachegrind.out')

        self.assertEqual(with_base, with_head)
        self.assertEqual(with_base['SWIFT_DETERMINISTIC_HASHING'], '1')

    def test_rayoc_runs_as_a_copy_at_the_same_path_wherever_it_was_built(self):
        with tempfile.TemporaryDirectory() as checkouts, tempfile.TemporaryDirectory() as directory:
            copies = []
            for checkout in ('a', 'a-checkout-at-a-longer-path'):
                built = os.path.join(checkouts, checkout, 'rayoc')
                os.makedirs(os.path.dirname(built))
                with open(built, 'w', encoding='utf-8') as f:
                    f.write(checkout)
                copies.append(copied_rayoc(built, directory))
                self.assertEqual(read(copies[-1]), checkout)
                self.assertFalse(os.path.islink(copies[-1]))

        self.assertEqual(copies[0], copies[1])

    def test_the_scratch_directory_has_one_path_length_whatever_the_temporary_directory_is(self):
        longer = self.enterContext(tempfile.TemporaryDirectory(prefix='a-longer-temporary-directory' * 3))
        lengths = []
        for temporary in ('/tmp', longer):
            with mock.patch.dict(os.environ, {'TMPDIR': temporary}), mock.patch('tempfile.tempdir', None):
                with scratch_directory() as directory:
                    lengths.append(len(directory))

        self.assertEqual(lengths[0], lengths[1])

    def test_a_cachegrind_file_with_no_summary_is_an_error(self):
        with self.assertRaises(ValueError):
            cachegrind_instructions(CACHEGRIND_OUT.replace('summary: 2647118212\n', ''))


class RegressionTests(unittest.TestCase):
    def test_a_rise_in_instructions_past_the_threshold_is_a_regression(self):
        baseline = {'check/loops-200': measures(1000, 1000), 'check/loops-400': measures(2000, 2000)}
        current = {'check/loops-200': measures(1051, 1000), 'check/loops-400': measures(2000, 2000)}

        self.assertEqual(regressions(baseline, current, threshold=5.0), [
            'check/loops-200: instructions rose 5.1%, past 5.0%',
        ])

    def test_memory_and_wall_time_fall_within_any_rise_and_instructions_within_a_rise_to_the_threshold(self):
        baseline = {'check/loops-200': measures(1000, 1000, seconds=1.0)}
        current = {'check/loops-200': measures(1050, 9000, seconds=9.0)}

        self.assertEqual(regressions(baseline, current, threshold=5.0), [])

    def test_instructions_either_run_lacks_and_a_benchmark_either_run_lacks_are_not_compared(self):
        baseline = {'check/loops-200': measures(None, 1000), 'check/loops-400': measures(1000, 1000)}
        current = {'check/loops-200': measures(9000, 1000), 'check/loops-800': measures(9000, 9000)}

        self.assertEqual(regressions(baseline, current, threshold=5.0), [])


class StageCostTests(unittest.TestCase):
    def test_what_each_run_does_past_checking_costs_the_difference_from_checking(self):
        current = {
            'check/loops-200': measures(280, 28),
            'emit-checked/loops-200': measures(300, 30),
            'emit-ir/loops-200': measures(330, 30),
            'compile-debug/loops-200': measures(900, 50),
            'compile-release/loops-200': measures(2000, 60),
        }

        self.assertEqual(stage_costs(current, 'loops-200'), {
            'printing the checked program': 20, 'printing the IR': 50, 'debug emitting': 620,
            'release emitting': 1720,
        })

    def test_a_stage_whose_runs_lack_a_count_has_no_cost(self):
        current = {'check/loops-200': measures(None, 28), 'emit-ir/loops-200': measures(330, 30)}

        self.assertEqual(stage_costs(current, 'loops-200'), {})


def baseline_of(results):
    return {'commit': '2042c3c1', 'code': 'main', 'date': '2026-11-23T10:00:00+00:00',
            'machine': {'processor': 'Apple M3 Pro'}, 'results': results}


class SummaryTests(unittest.TestCase):
    def test_a_summary_tables_each_benchmark(self):
        results = {'check/loops-200': measures(2647118212, 40322368, seconds=0.152)}

        self.assertEqual(summary(results, 'rayoc at 1a2b3c4d'), '''\
### Benchmarks of rayoc at 1a2b3c4d

Instructions and peak memory are as the system reports them for rayoc's process.

| Benchmark | Instructions | Peak memory | Wall time |
| --- | ---: | ---: | ---: |
| check/loops-200 | 2,647 M | 38.5 MiB | 152 ms |
''')

    def test_a_summary_with_a_baseline_gives_each_change_from_it_and_lists_each_measure_that_rose(self):
        baseline = baseline_of({'check/loops-200': measures(1000, 2000, seconds=0.2)})
        results = {'check/loops-200': measures(1100, 1990, seconds=0.3), 'check/loops-400': measures(2000, 4000)}

        self.assertEqual(summary(results, 'rayoc at 1a2b3c4d', baseline, ['check/loops-200: rose']), '''\
### Benchmarks of rayoc at 1a2b3c4d

Instructions and peak memory are as the system reports them for rayoc's process.

Compared with the baseline 2042c3c1 (main), measured 2026-11-23T10:00:00+00:00 on Apple M3 Pro.

| Benchmark | Instructions | Change | Peak memory | Change | Wall time | Wall time of the baseline |
| --- | ---: | ---: | ---: | ---: | ---: | ---: |
| check/loops-200 | 0 M | +10.00% | 0.0 MiB | -0.50% | 300 ms | 200 ms |
| check/loops-400 | 0 M | - | 0.0 MiB | - | 1,000 ms | - |

These rose past the threshold:

- check/loops-200: rose
''')

    def test_a_summary_of_instructions_valgrind_counted_says_so(self):
        results = {'check/loops-200': measures(2647118212, 40322368)}

        self.assertIn("\nInstructions are as Valgrind's Cachegrind counts them, within 0.002% from run to run, and "
                      'peak memory as the system reports it for a run outside Valgrind.\n',
                      summary(results, 'rayoc', counter='valgrind'))

    def test_a_summary_with_a_baseline_says_where_nothing_rose(self):
        baseline = baseline_of({'check/loops-200': measures(1000, 1000)})

        self.assertIn('\nNothing rose past the threshold.\n', summary({'check/loops-200': measures(1000, 1000)},
                                                                       'rayoc', baseline, []))

    def test_a_summary_of_results_with_no_instruction_count_says_nothing_was_compared(self):
        results = {'check/loops-200': measures(None, 1000)}
        baseline = baseline_of({'check/loops-200': measures(None, 900)})

        self.assertIn('| check/loops-200 | - |', summary(results, 'rayoc'))
        self.assertIn(UNCOUNTED, summary(results, 'rayoc'))
        self.assertIn('| check/loops-200 | - | - | 0.0 MiB | +11.11% |', summary(results, 'rayoc', baseline, []))
        self.assertNotIn('Nothing rose', summary(results, 'rayoc', baseline, []))
        self.assertNotIn(UNCOUNTED, summary({'check/loops-200': measures(1000, 1000)}, 'rayoc'))


class ArgumentTests(unittest.TestCase):
    def test_stops_names_the_stop_points_to_measure_in_the_order_rayoc_reaches_them(self):
        self.assertEqual(parse_arguments(['--stops', 'compile-debug,check']).stops, ['check', 'compile-debug'])
        self.assertEqual(parse_arguments([]).stops, [stop for stop, _ in STOP_POINTS])

    def test_a_stop_point_rayoc_has_none_of_is_an_error(self):
        with self.assertRaises(SystemExit), contextlib.redirect_stderr(io.StringIO()):
            parse_arguments(['--stops', 'check,link'])

    def test_the_threshold_is_the_counters_unless_named(self):
        self.assertEqual(parse_arguments([]).threshold, 5.0)
        self.assertEqual(parse_arguments(['--counter', 'valgrind']).threshold, 1.0)
        self.assertEqual(parse_arguments(['--counter', 'valgrind', '--threshold', '3']).threshold, 3.0)


class ComparisonTests(unittest.TestCase):
    def test_a_baseline_counted_another_way_is_not_compared(self):
        # A run that went on to build rayoc would take minutes, so the build fails at once.
        unbuilt = mock.patch('benchmark.built_rayoc', side_effect=AssertionError('rayoc was built'))
        with tempfile.TemporaryDirectory() as directory, mock.patch('benchmark.BASELINES', directory), unbuilt:
            with open(os.path.join(directory, '2042c3c1.json'), 'w', encoding='utf-8') as f:
                json.dump({**baseline_of({}), 'counter': 'valgrind'}, f)
            errors = io.StringIO()
            with contextlib.redirect_stderr(errors):
                status = main(['--compare', '2042c3c1'])

        self.assertEqual(status, 2)
        self.assertIn('the baseline 2042c3c1 counted instructions with the valgrind counter, and this run uses the '
                      'system counter', errors.getvalue())


